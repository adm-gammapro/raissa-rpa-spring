    public static Optional<String> classify(String pathData) throws ParseException {
        double[] candidate = SvgRasterizer.fingerprint(pathData);
        String bestDigit = null;
        double bestScore = Double.MAX_VALUE;

        for (Map.Entry<String, double[]> entry : REFERENCE_FINGERPRINTS.entrySet()) {
            double score = meanSquaredError(candidate, entry.getValue());
            if (score < bestScore) {
                bestScore = score;
                bestDigit = entry.getKey();
            }
        }

        if (bestDigit != null && bestScore <= MATCH_THRESHOLD) {
            return Optional.of(bestDigit);
        }
        return Optional.empty();
    }

    private static void register(Map<String, double[]> map, String digit, String pathData) {
        try {
            map.put(digit, SvgRasterizer.fingerprint(pathData));
        } catch (ParseException ex) {
            throw new IllegalStateException("No se pudo registrar el dígito " + digit + ": " + ex.getMessage(), ex);
        }
    }

    private static double meanSquaredError(double[] a, double[] b) {
        double acc = 0.0;
        for (int i = 0; i < a.length; i++) {
            double diff = a[i] - b[i];
            acc += diff * diff;
        }
        return acc / a.length;
    }
